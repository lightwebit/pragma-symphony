    #[test]
    fn a_pure_cache_hit_keeps_the_known_ttl() {
        let conn = in_memory_db();
        insert_scheduled_project(&conn, "p1");
        conn.execute(
            "INSERT INTO sessions (id, project_id, started_at, saved) VALUES ('s', 'p1', '2026-09-01', 0)",
            [],
        )
        .unwrap();

        let snap = |ctx, ttl| CacheSnapshot {
            context_tokens: ctx,
            ttl_secs: ttl,
        };
        update_session_cache_on(&conn, "s", snap(40_000, Some(3600)), "2026-09-23T08:00:00Z")
            .unwrap();
        update_session_cache_on(&conn, "s", snap(41_000, None), "2026-09-23T08:01:00Z").unwrap();

        let (ctx, ttl, at): (i64, Option<i64>, String) = conn
            .query_row(
                "SELECT last_context_tokens, cache_ttl_secs, last_call_at FROM sessions WHERE id = 's'",
                [],
                |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?)),
            )
            .unwrap();
        assert_eq!(
            (ctx, ttl, at.as_str()),
            (41_000, Some(3600), "2026-09-23T08:01:00Z")
        );
    }
