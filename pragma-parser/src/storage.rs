fn slugify(title: &str) -> String {
    title
        .trim()
        .to_lowercase()
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '_' })
        .collect::<String>()
        .split('_')
        .filter(|s| !s.is_empty())
        .collect::<Vec<_>>()
        .join("_")
}

fn unique_slug(conn: &Connection, base: &str) -> String {
    let mut candidate = base.to_string();
    let mut counter = 2u32;
    loop {
        let exists: bool = conn
            .query_row(
                "SELECT 1 FROM projects WHERE slug = ?1",
                params![candidate],
                |_| Ok(true),
            )
            .unwrap_or(false);
        if !exists {
            return candidate;
        }
        candidate = format!("{}_{}", base, counter);
        counter += 1;
    }
}

