/// Replaces a project's steps wholesale. Deliberately not a per-step CRUD:
/// the order is part of the data, and rewriting the whole list avoids
/// reconciling positions after a reorder or a delete in the UI.
pub fn replace_pipeline_steps(project_id: &str, steps: &[PipelineStep]) -> Result<()> {
    let mut conn = open_db()?;
    let tx = conn.transaction()?;
    tx.execute(
        "DELETE FROM pipeline_steps WHERE project_id = ?1",
        params![project_id],
    )?;
    for (position, step) in steps.iter().enumerate() {
        tx.execute(
            "INSERT INTO pipeline_steps (id, project_id, position, label, command, kind, enabled)
             VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7)",
            params![
                step.id,
                project_id,
                position as i64,
                step.label,
                step.command,
                step.kind,
                step.enabled as i32,
            ],
        )?;
    }
    tx.commit()?;
    Ok(())
}

