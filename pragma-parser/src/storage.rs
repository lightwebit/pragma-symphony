    fn v12_db_gains_sessions_model_without_losing_sessions() {
        // 12→13 is the first additive migration that touches a column of an
        // *existing* table (not just new tables): a real DB with saved sessions
        // must not lose them just because sessions gains `model`.
        const V12_SESSIONS: &str = "
            CREATE TABLE sessions (
                id                 TEXT PRIMARY KEY,
                project_id         TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                started_at         TEXT NOT NULL,
                command            TEXT,
                saved              INTEGER NOT NULL DEFAULT 0,
                title              TEXT,
                working_dir        TEXT,
                input_tokens       INTEGER NOT NULL DEFAULT 0,
                output_tokens      INTEGER NOT NULL DEFAULT 0,
                cache_read_tokens  INTEGER NOT NULL DEFAULT 0,
                cache_write_tokens INTEGER NOT NULL DEFAULT 0,
                total_cost_usd     REAL,
                attachments        TEXT,
                git_branch         TEXT,
                git_base           TEXT
            );
        ";
        let conn = Connection::open_in_memory().unwrap();
        conn.execute_batch(INIT_PRAGMA).unwrap();
        conn.execute_batch(CURRENT_TABLES).unwrap();
        conn.execute_batch("DROP TABLE sessions").unwrap();
        conn.execute_batch(V12_SESSIONS).unwrap();
        conn.execute_batch("INSERT INTO schema_version (version) VALUES (12)")
            .unwrap();

        insert_scheduled_project(&conn, "p1");
        let now = Utc::now().to_rfc3339();
        conn.execute(
            "INSERT INTO sessions (id, project_id, started_at, saved) VALUES ('s1', 'p1', ?1, 1)",
            params![now],
        )
        .unwrap();

        init_db(&conn).unwrap();

        assert_eq!(get_schema_version(&conn).unwrap(), CURRENT_SCHEMA_VERSION);
        let (id, model): (String, Option<String>) = conn
            .query_row("SELECT id, model FROM sessions WHERE id = 's1'", [], |r| {
                Ok((r.get(0)?, r.get(1)?))
            })
            .unwrap();
        assert_eq!(
            id, "s1",
            "the additive migration deleted the existing session"
        );
        assert_eq!(model, None, "a pre-existing session has no recorded model");

        // The column is writable as usual after the migration.
        conn.execute(
            "INSERT INTO sessions (id, project_id, started_at, saved, model) VALUES ('s2', 'p1', ?1, 1, 'opus')",
            params![now],
        )
        .unwrap();
    }

