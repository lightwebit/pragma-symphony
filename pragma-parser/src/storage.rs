fn sanitize_fts_query(query: &str) -> String {
    query
        .split_whitespace()
        .filter(|t| !t.is_empty())
        .map(|t| format!("\"{}\"*", t.replace('"', "\"\"")))
        .collect::<Vec<_>>()
        .join(" ")
}

/// Full-text search across a project's sessions.
pub fn search_sessions_for_project(project_id: &str, query: &str) -> Result<Vec<SessionInfo>> {
    if query.trim().is_empty() {
        return list_sessions_for_project(project_id);
    }
    let db_path = pragma_db_path()?;
    if !db_path.exists() {
        return Ok(vec![]);
    }
    let conn = open_db()?;
    let safe_query = sanitize_fts_query(query);
    let sql = format!(
        "{SESSION_SELECT}
         JOIN (SELECT DISTINCT session_id FROM sessions_fts WHERE sessions_fts MATCH ?1) f
              ON f.session_id = s.id
         WHERE s.project_id = ?2
         GROUP BY s.id
         ORDER BY s.started_at DESC"
    );
    let mut stmt = conn.prepare(&sql)?;
    let rows = stmt.query_map(params![safe_query, project_id], row_to_session_info)?;
    rows.collect::<Result<Vec<_>, _>>().map_err(Into::into)
}

