    #[test]
    fn cache_snapshot_reads_context_and_ttl_from_usage() {
        let one_hour = serde_json::json!({
            "input_tokens": 2, "output_tokens": 300,
            "cache_read_input_tokens": 33_457, "cache_creation_input_tokens": 1_108,
            "cache_creation": { "ephemeral_5m_input_tokens": 0, "ephemeral_1h_input_tokens": 1_108 }
        });
        assert_eq!(
            cache_snapshot_from_usage(&one_hour),
            Some(CacheSnapshot {
                context_tokens: 34_867,
                ttl_secs: Some(3600)
            })
        );

        let five_min = serde_json::json!({
            "input_tokens": 1, "output_tokens": 0,
            "cache_read_input_tokens": 0, "cache_creation_input_tokens": 500,
            "cache_creation": { "ephemeral_5m_input_tokens": 500, "ephemeral_1h_input_tokens": 0 }
        });
        assert_eq!(
            cache_snapshot_from_usage(&five_min).unwrap().ttl_secs,
            Some(300)
        );

        // Pure hit: nothing written, the lifetime cannot be inferred from this call.
        let hit = serde_json::json!({
            "input_tokens": 2, "output_tokens": 3, "cache_read_input_tokens": 33_457,
            "cache_creation_input_tokens": 0,
            "cache_creation": { "ephemeral_5m_input_tokens": 0, "ephemeral_1h_input_tokens": 0 }
        });
        assert_eq!(cache_snapshot_from_usage(&hit).unwrap().ttl_secs, None);

        // The test fake claude and old versions of the CLI have no `cache_creation`.
        let legacy = serde_json::json!({ "input_tokens": 1, "output_tokens": 5 });
        assert_eq!(cache_snapshot_from_usage(&legacy).unwrap().ttl_secs, None);

        assert_eq!(cache_snapshot_from_usage(&serde_json::json!({})), None);
        assert_eq!(cache_snapshot_from_usage(&serde_json::Value::Null), None);
    }

