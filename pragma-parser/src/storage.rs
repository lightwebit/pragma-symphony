/// The account in `DOMAIN\user` form (for a local account the domain is the machine
/// name): with the bare name, a domain account and a local one with the same name are ambiguous.
#[cfg_attr(not(windows), allow(dead_code))]
fn qualified_account(domain: Option<&str>, user: &str) -> Option<String> {
    let user = user.trim();
    if user.is_empty() {
        return None;
    }
    Some(match domain.map(str::trim).filter(|d| !d.is_empty()) {
        Some(d) => format!("{d}\\{user}"),
        None => user.to_string(),
    })
}

#[cfg(windows)]
fn restrict_to_owner(path: &std::path::Path) {
    let Some(path_str) = path.to_str() else {
        return;
    };
    let domain = std::env::var("USERDOMAIN").ok();
    let user = std::env::var("USERNAME").unwrap_or_default();
    let Some(account) = qualified_account(domain.as_deref(), &user) else {
        return;
    };
    // Absolute path, not `icacls` looked up in PATH: with a PATH lacking System32 (it has
    // happened) the call failed silently, and a bare name runs the
    // first `icacls.exe` it finds.
    let icacls = std::env::var_os("SystemRoot")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| std::path::PathBuf::from(r"C:\Windows"))
        .join("System32")
        .join("icacls.exe");
    let _ = std::process::Command::new(icacls)
        .args([
            path_str,
            "/inheritance:r",
            "/grant:r",
            &format!("{account}:(OI)(CI)F"),
        ])
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status();
}

#[cfg(unix)]
fn restrict_to_owner(path: &std::path::Path) {
    use std::os::unix::fs::PermissionsExt;
    let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o700));
}

#[cfg(not(any(windows, unix)))]
fn restrict_to_owner(_path: &std::path::Path) {}

static PRAGMA_DIR_SECURED: std::sync::OnceLock<()> = std::sync::OnceLock::new();

pub fn pragma_db_path() -> Result<std::path::PathBuf> {
    let home = std::env::var_os("HOME")
        .or_else(|| std::env::var_os("USERPROFILE"))
        .map(std::path::PathBuf::from)
        .context("HOME directory not found")?;
    let dir = home.join(".pragma");
    std::fs::create_dir_all(&dir)?;
    PRAGMA_DIR_SECURED.get_or_init(|| restrict_to_owner(&dir));
    Ok(dir.join("pragma.db"))
}

