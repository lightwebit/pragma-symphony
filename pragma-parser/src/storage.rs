// Run once to set the PRAGMAs and the version table.
const INIT_PRAGMA: &str = "
PRAGMA journal_mode = WAL;
PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL DEFAULT 0);
";

// Full tables of the current schema. All with IF NOT EXISTS — idempotent.
const CURRENT_TABLES: &str = "
-- slug: generated once from `title` (slugify + a _2/_3... suffix on collision),
-- never regenerated by update_project.
-- test_command/lint_command/coverage_command: optional shell commands run by the
-- VERIFY phase (see verify.rs). verify_baseline: JSON with the names of the tests that
-- were already failing when VERIFY was first enabled for this project — only *new* failures
-- compared with this baseline block the gate.
-- review_invariants: free text with the invariants the REVIEW phase must check
-- on every diff (contracts, parity with legacy, conventions...). Injected into the
-- separate review session (see review.rs). Empty = generic review.
-- sensitive_paths: globs (one per line) of the project's sensitive surfaces — auth,
-- dynamic queries/commands, filesystem, secrets. If the diff touches one of these paths the
-- REVIEW session also gets the security hand-off (see review.rs). Empty =
-- Pragma uses its default patterns, never fewer checks.
-- e2e_command/e2e_precondition/e2e_runner: configuration of the on-demand E2E run.
-- Written only by the E2E popup via update_e2e_config, never by the project form — the
-- config lives here, while generated specs and scripts live in <working_dir>/.autoTest/ (see e2e.rs).
-- e2e_precondition is text Pragma shows before the run (e.g. requires the app on :5173):
-- in v1 it does not orchestrate the environment, it only declares it.
-- project_category/project_stack: category requested by the client (e.g. Desktop app) and
-- the stack derived from the hard-wired category→stack table. Free fields (TEXT, no
-- CHECK): the catalogue lives in the Rust code and must be able to grow without a migration —
-- a stack outside the catalogue is legitimate, just without an automatically proposed live command.
-- Written by the project form or by discovery via brief/manifest, always correctable
-- by the user.
-- live_command: shell command of the on-demand Live button. NULL = not configured (the
-- button stays off), same pattern as e2e_command — written by the Live popup,
-- not by the project form.
CREATE TABLE IF NOT EXISTS projects (
    id                TEXT PRIMARY KEY,
    title             TEXT NOT NULL,
    slug              TEXT NOT NULL UNIQUE,
    description       TEXT,
    working_dir       TEXT,
    color             TEXT,
    test_command      TEXT,
    lint_command      TEXT,
    coverage_command  TEXT,
    verify_baseline   TEXT,
    review_invariants TEXT,
    e2e_command       TEXT,
    e2e_precondition  TEXT,
    e2e_runner        TEXT,
    sensitive_paths   TEXT,
    project_category  TEXT,
    project_stack     TEXT,
    live_command      TEXT,
    created_at        TEXT NOT NULL,
    updated_at        TEXT NOT NULL
);

-- Steps of the local pipeline (build/test/publish in sequence, fail-fast) — generalizes
-- VERIFY instead of duplicating its execution logic. position sets the order,
-- enabled lets a step be switched off without losing it. No status column:
-- the outcome of a run is not written here, it is per execution (same principle as
-- .autoTest/runs/ for E2E, see e2e.rs).
--
-- kind: 'command' = normal step, the outcome is the exit code. 'verify' = delegates to the
-- project's VERIFY phase (test_command + classification + baseline of pre-existing
-- failures, see verify.rs), and `command` is ignored.
-- Why it exists: on a project whose tests are already red, an exit-code-only step
-- would make the pipeline permanently red, hence useless. The baseline that solves
-- that problem lives in verify.rs and must stay in ONE place — duplicating it here
-- is exactly the divergence this design set out to avoid.
CREATE TABLE IF NOT EXISTS pipeline_steps (
    id          TEXT PRIMARY KEY,
    project_id  TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    position    INTEGER NOT NULL,
    label       TEXT NOT NULL,
    command     TEXT NOT NULL,
    kind        TEXT NOT NULL DEFAULT 'command',
    enabled     INTEGER NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS idx_pipeline_steps_project ON pipeline_steps(project_id, position);

-- git_branch: name of the `pragma/<session-id>` session branch created by Pragma at the
-- start of a session in versioned working dirs (see git_branch.rs). NULL = not created
-- (non-git working dir, option disabled, or creation failed).
-- git_base: SHA of the commit the session branch was forked from. It is the base of the
-- diff fed to the REVIEW phase (`git diff <git_base>`), so it stays computable
-- even sessions or restarts later. NULL when git_branch is NULL.
-- model: alias chosen for the FIRST turn of the session ('sonnet'/'opus'/'fable'),
-- written once at creation (never rewritten on resume/send_control — a model
-- change mid-session does not reopen this row, see start_session_core).
-- NULL = session created before this field existed (v12 and earlier).
-- last_context_tokens / cache_ttl_secs / last_call_at (v15): snapshot of the last
-- API call — context size, lifetime of the cache it was written with
-- (300 or 3600) and when. They tell, before a --resume, whether the cache has expired and
-- how much context will be rewritten. NULL on earlier sessions.
CREATE TABLE IF NOT EXISTS sessions (
    id                 TEXT PRIMARY KEY,
    project_id         TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    started_at         TEXT NOT NULL,
    command            TEXT,
    saved              INTEGER NOT NULL DEFAULT 0,
    title              TEXT,
    working_dir        TEXT,
    input_tokens       INTEGER NOT NULL DEFAULT 0,
    output_tokens      INTEGER NOT NULL DEFAULT 0,
    cache_read_tokens  INTEGER NOT NULL DEFAULT 0,
    cache_write_tokens INTEGER NOT NULL DEFAULT 0,
    total_cost_usd     REAL,
    attachments        TEXT,
    git_branch         TEXT,
    git_base           TEXT,
    model              TEXT,
    last_context_tokens INTEGER,
    cache_ttl_secs     INTEGER,
    last_call_at       TEXT
);

CREATE TABLE IF NOT EXISTS atoms (
    id          TEXT PRIMARY KEY,
    session_id  TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    atom_type   TEXT NOT NULL,
    file_path   TEXT,
    file_type   TEXT,
    action      TEXT,
    content     TEXT NOT NULL,
    collapsed   INTEGER NOT NULL DEFAULT 0,
    source      TEXT NOT NULL,
    received_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_atoms_session    ON atoms(session_id);
CREATE INDEX IF NOT EXISTS idx_sessions_project ON sessions(project_id, started_at DESC);
-- `saved` and this index are vestigial — no query reads them any more
-- (no migration, the column stays for compatibility with existing databases).
CREATE INDEX IF NOT EXISTS idx_sessions_saved   ON sessions(saved, started_at DESC);

CREATE VIRTUAL TABLE IF NOT EXISTS sessions_fts USING fts5(
    session_id UNINDEXED,
    body,
    tokenize='unicode61'
);

CREATE TRIGGER IF NOT EXISTS fts_atoms_insert
AFTER INSERT ON atoms BEGIN
    INSERT INTO sessions_fts(session_id, body) VALUES (NEW.session_id, NEW.content);
END;

CREATE TRIGGER IF NOT EXISTS fts_sessions_title
AFTER UPDATE OF title ON sessions WHEN NEW.title IS NOT NULL BEGIN
    INSERT INTO sessions_fts(session_id, body) VALUES (NEW.id, NEW.title);
END;

-- Scheduled sessions: prompt + start time, waiting for the scheduler
-- (src-tauri/src/scheduler.rs) to fire them. They are not sessions: a row here
-- becomes a row in `sessions` only when it fires, and from then on the two
-- live separately — cancelling the schedule does not touch the session already started.
--
-- binary/config_dir are deliberately NOT stored: they are resolved at fire time
-- from `profile_label` against the current settings. A binary path frozen
-- weeks earlier is exactly the kind of data that rots.
--
-- status:
--   pending   waiting for the time
--   queued    time has come but the working dir is busy — retried on every tick
--   fired     started: session_id filled in
--   cancelled cancelled by the user
--   missed    the time passed while the app was closed; waits for the user's choice
CREATE TABLE IF NOT EXISTS scheduled_sessions (
    id            TEXT PRIMARY KEY,
    project_id    TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    prompt        TEXT NOT NULL,
    run_at        TEXT NOT NULL,
    working_dir   TEXT,
    profile_label TEXT,
    model         TEXT,
    attachments   TEXT,
    title         TEXT,
    step_by_step  INTEGER NOT NULL DEFAULT 0,
    auto_confirm  INTEGER NOT NULL DEFAULT 1,
    status        TEXT NOT NULL DEFAULT 'pending',
    session_id    TEXT,
    last_error    TEXT,
    created_at    TEXT NOT NULL,
    updated_at    TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_scheduled_due ON scheduled_sessions(status, run_at);
CREATE INDEX IF NOT EXISTS idx_scheduled_project ON scheduled_sessions(project_id, run_at);

-- The user's checklist, per project. Hand-written notes on what is left to do:
-- nothing to do with the pragma protocol phases (PLAN/STEP_COMPLETE), which
-- describe what the model is doing inside ONE session and live in the atoms.
-- Nobody but the user ever writes here.
--
-- Attached to the project and not to the session on purpose: sessions in Pragma
-- are created all the time (the `+`, the ClosingCard, a resume) and a list that vanishes
-- with every new session would not help anyone remember anything. It therefore survives
-- all the sessions of the project, and dies only with the project (ON DELETE CASCADE).
--
-- position: insertion order, assigned as max+1. Checking a row does not
-- move it — a checklist that reorders under the cursor while you read it
-- makes you lose your place.
CREATE TABLE IF NOT EXISTS todos (
    id         TEXT PRIMARY KEY,
    project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    text       TEXT NOT NULL,
    done       INTEGER NOT NULL DEFAULT 0,
    position   INTEGER NOT NULL,
    created_at TEXT NOT NULL,
    done_at    TEXT
);

CREATE INDEX IF NOT EXISTS idx_todos_project ON todos(project_id, position);
";

