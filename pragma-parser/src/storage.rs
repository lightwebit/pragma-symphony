fn get_schema_version(conn: &Connection) -> Result<u32> {
    conn.query_row("SELECT version FROM schema_version LIMIT 1", [], |r| {
        r.get(0)
    })
    .or_else(|_| {
        conn.execute("INSERT INTO schema_version (version) VALUES (0)", [])?;
        Ok(0)
    })
}

fn set_schema_version(conn: &Connection, v: u32) -> Result<()> {
    conn.execute("UPDATE schema_version SET version = ?1", params![v])?;
    Ok(())
}

/// Columns added to `sessions` after its creation: v13 `model`, v15 the cache
/// snapshot. Name and type come only from this list, never from external input.
const SESSIONS_ADDED_COLUMNS: &[(&str, &str)] = &[
    ("model", "TEXT"),
    ("last_context_tokens", "INTEGER"),
    ("cache_ttl_secs", "INTEGER"),
    ("last_call_at", "TEXT"),
];

/// Adds the missing columns to `sessions`. `ALTER TABLE ... ADD COLUMN IF NOT
/// EXISTS` is not guaranteed on the SQLite version bundled by rusqlite, so
/// `pragma_table_info` is checked by hand instead of relying on the syntax.
fn ensure_sessions_columns(conn: &Connection) -> Result<()> {
    for (name, ty) in SESSIONS_ADDED_COLUMNS {
        let exists: bool = conn
            .prepare("SELECT 1 FROM pragma_table_info('sessions') WHERE name = ?1")?
            .exists(params![name])?;
        if !exists {
            conn.execute_batch(&format!("ALTER TABLE sessions ADD COLUMN {name} {ty}"))?;
        }
    }
    Ok(())
}

// ---------------------------------------------------------------------------
// DB init — breaking migration if version < 9
// ---------------------------------------------------------------------------
//
// Early versions made no promise that saved data would survive a schema
// change. The incremental additive migrations (v3→v8) that preserved data between
// versions were removed together with their test coverage: any DB below the
// threshold is recreated from scratch. From v10 on the rule is the opposite
// (see below): migrations are additive and never drop data.

fn init_db(conn: &Connection) -> Result<()> {
    conn.execute_batch(INIT_PRAGMA)?;

    let version = get_schema_version(conn)?;

    if (10..CURRENT_SCHEMA_VERSION).contains(&version) {
        // Additive jumps from v10 on: 10→11 added `scheduled_sessions`, 11→12
        // added `todos`. In all these cases it is just a new table, no existing
        // table changes shape. Dropping everything here would delete real projects and
        // sessions to add an empty table — cost with no return.
        // Drop-and-recreate remains the rule for every version below 10, where the
        // jumps were truly incompatible.
        conn.execute_batch(CURRENT_TABLES)?;
        // 12→13 and 14→15: columns added to an *existing* table rather than a new
        // table — CREATE TABLE IF NOT EXISTS above does not touch `sessions` if it
        // is already there. Idempotent: skips columns that already exist (user already
        // updated, or DB created from scratch with CURRENT_TABLES, which includes them).
        ensure_sessions_columns(conn)?;
        set_schema_version(conn, CURRENT_SCHEMA_VERSION)?;
    } else if version < CURRENT_SCHEMA_VERSION {
        // Incompatible or obsolete schema — drop everything old, no
        // data migration.
        conn.execute_batch(
            "DROP TABLE IF EXISTS todos;
             DROP TABLE IF EXISTS scheduled_sessions;
             DROP TRIGGER IF EXISTS fts_atoms_insert;
             DROP TRIGGER IF EXISTS fts_sessions_title;
             DROP TABLE IF EXISTS sessions_fts;
             DROP TABLE IF EXISTS pipeline_steps;
             DROP TABLE IF EXISTS atoms;
             DROP TABLE IF EXISTS sessions;
             DROP TABLE IF EXISTS projects;",
        )?;
        conn.execute_batch(CURRENT_TABLES)?;
        set_schema_version(conn, CURRENT_SCHEMA_VERSION)?;
    } else {
        // Already at the current version: make sure the tables exist (idempotent).
        conn.execute_batch(CURRENT_TABLES)?;
    }

    Ok(())
}

