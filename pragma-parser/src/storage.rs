/// Moves overdue `pending`/`queued` rows to `missed` and returns the ones
/// touched — called once at app start, to tell
/// "waiting" from "the app was closed when it should have started".
pub fn mark_overdue_as_missed(now: &str) -> Result<Vec<ScheduledSession>> {
    let db_path = pragma_db_path()?;
    if !db_path.exists() {
        return Ok(vec![]);
    }
    let mut conn = open_db()?;
    let tx = conn.transaction()?;

    let overdue: Vec<ScheduledSession> = {
        let sql = format!(
            "SELECT {SCHEDULED_SELECT_COLUMNS} FROM scheduled_sessions
             WHERE status IN ('pending', 'queued') AND run_at <= ?1"
        );
        let mut stmt = tx.prepare(&sql)?;
        let rows = stmt.query_map(params![now], row_to_scheduled)?;
        rows.collect::<Result<Vec<_>, _>>()?
    };

    if !overdue.is_empty() {
        let updated_at = Utc::now().to_rfc3339();
        for row in &overdue {
            tx.execute(
                "UPDATE scheduled_sessions SET status = 'missed', updated_at = ?1 WHERE id = ?2",
                params![updated_at, row.id],
            )?;
        }
    }

    tx.commit()?;
    Ok(overdue
        .into_iter()
        .map(|mut r| {
            r.status = "missed".to_string();
            r
        })
        .collect())
}

