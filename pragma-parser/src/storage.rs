/// Adds an item at the end. `text` already arrives cleaned by the caller.
pub fn create_todo(project_id: &str, text: &str) -> Result<Todo> {
    let conn = open_db()?;
    let id = Uuid::new_v4().to_string();
    let now = Utc::now().to_rfc3339();

    // MAX+1 and not COUNT(*): the new position must be greater than all the
    // *live* ones, not equal to how many rows there are. After deleting an item in the middle, COUNT
    // would return a value already taken by an existing row and the two would end up
    // tied, with the order decided by SQLite. The gaps left at the end by
    // deletions are reused instead, which is correct: that row is gone.
    let position: i64 = conn.query_row(
        "SELECT COALESCE(MAX(position), -1) + 1 FROM todos WHERE project_id = ?1",
        params![project_id],
        |r| r.get(0),
    )?;

    conn.execute(
        "INSERT INTO todos (id, project_id, text, done, position, created_at)
         VALUES (?1, ?2, ?3, 0, ?4, ?5)",
        params![id, project_id, text, position, now],
    )?;

    Ok(Todo {
        id,
        project_id: project_id.to_string(),
        text: text.to_string(),
        done: false,
        position,
        created_at: now,
        done_at: None,
    })
}

