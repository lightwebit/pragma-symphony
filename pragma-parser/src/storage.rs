/// Token di una sessione: input, output, cache read, cache write.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Usage {
    pub input: u64,
    pub output: u64,
    pub cache_read: u64,
    pub cache_write: u64,
}

impl std::ops::Add for Usage {
    type Output = Usage;
    fn add(self, o: Usage) -> Usage {
        Usage {
            input: self.input + o.input,
            output: self.output + o.output,
            cache_read: self.cache_read + o.cache_read,
            cache_write: self.cache_write + o.cache_write,
        }
    }
}

/// The tokens already recorded for the session (zero if the row is not there yet). It is the base of a
/// turn: `claude -p --resume` reports only the tokens of its own turn, not of the session.
pub fn load_session_usage(session_id: &str) -> Result<Usage> {
    load_session_usage_on(&open_db()?, session_id)
}

fn load_session_usage_on(conn: &Connection, session_id: &str) -> Result<Usage> {
    Ok(conn
        .query_row(
            "SELECT input_tokens, output_tokens, cache_read_tokens, cache_write_tokens
               FROM sessions WHERE id = ?1",
            params![session_id],
            |r| {
                Ok(Usage {
                    input: r.get::<_, i64>(0)? as u64,
                    output: r.get::<_, i64>(1)? as u64,
                    cache_read: r.get::<_, i64>(2)? as u64,
                    cache_write: r.get::<_, i64>(3)? as u64,
                })
            },
        )
        .map(Some)
        .or_else(|e| match e {
            rusqlite::Error::QueryReturnedNoRows => Ok(None),
            e => Err(e),
        })?
        .unwrap_or_default())
}

/// Writes the session's tokens, already summed by the caller (turn base + turn). The cost
/// is taken as it is: the CLI's `total_cost_usd` already covers the whole session even after a resume
/// (e.g. $0.80 with 87k cache-read tokens in the turn alone). `None` (`assistant` messages do not
/// carry it) leaves what is there.
pub fn update_session_usage(
    session_id: &str,
    usage: Usage,
    total_cost_usd: Option<f64>,
) -> Result<()> {
    update_session_usage_on(&open_db()?, session_id, usage, total_cost_usd)
}

fn update_session_usage_on(
    conn: &Connection,
    session_id: &str,
    usage: Usage,
    total_cost_usd: Option<f64>,
) -> Result<()> {
    conn.execute(
        "UPDATE sessions SET input_tokens=?1, output_tokens=?2, cache_read_tokens=?3,
         cache_write_tokens=?4, total_cost_usd=COALESCE(?5, total_cost_usd) WHERE id=?6",
        params![
            usage.input as i64,
            usage.output as i64,
            usage.cache_read as i64,
            usage.cache_write as i64,
            total_cost_usd,
            session_id
        ],
    )?;
    Ok(())
}

/// What an API call leaves in the cache: how large the context is that the next
/// call will have to re-read (or rewrite, if the cache has expired) and with what lifetime it was
/// written. `ttl_secs` is `None` when the call wrote nothing to the cache (pure
/// hit): the lifetime stays the one already recorded.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CacheSnapshot {
    pub context_tokens: u64,
    pub ttl_secs: Option<u64>,
}

/// Reads the `usage` object of a stream-json `assistant` message. The context is the whole
/// prompt of the call (input + read + written to cache) plus the output, which becomes
/// part of the next prompt. The lifetime comes from the `cache_creation` split: the CLI writes
/// at 5 minutes or 1 hour depending on the account.
pub fn cache_snapshot_from_usage(u: &serde_json::Value) -> Option<CacheSnapshot> {
    if !u.is_object() {
        return None;
    }
    let n = |k: &str| u[k].as_u64().unwrap_or(0);
    let context_tokens = n("input_tokens")
        + n("cache_read_input_tokens")
        + n("cache_creation_input_tokens")
        + n("output_tokens");
    if context_tokens == 0 {
        return None;
    }
    let cc = &u["cache_creation"];
    let ttl_secs = if cc["ephemeral_1h_input_tokens"].as_u64().unwrap_or(0) > 0 {
        Some(3600)
    } else if cc["ephemeral_5m_input_tokens"].as_u64().unwrap_or(0) > 0 {
        Some(300)
    } else {
        None
    };
    Some(CacheSnapshot {
        context_tokens,
        ttl_secs,
    })
}

/// Records the snapshot of the last call. `at` is RFC 3339. A `None` lifetime does not
/// overwrite the one already written: a pure hit renews the cache with the previous lifetime.
pub fn update_session_cache(session_id: &str, snap: CacheSnapshot, at: &str) -> Result<()> {
    update_session_cache_on(&open_db()?, session_id, snap, at)
}

fn update_session_cache_on(
    conn: &Connection,
    session_id: &str,
    snap: CacheSnapshot,
    at: &str,
) -> Result<()> {
    conn.execute(
        "UPDATE sessions SET last_context_tokens=?1,
         cache_ttl_secs=COALESCE(?2, cache_ttl_secs), last_call_at=?3 WHERE id=?4",
        params![
            snap.context_tokens as i64,
            snap.ttl_secs.map(|v| v as i64),
            at,
            session_id
        ],
    )?;
    Ok(())
}

