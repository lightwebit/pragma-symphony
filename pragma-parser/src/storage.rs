#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ProjectInfo {
    pub id: String,
    pub title: String,
    pub slug: String,
    pub description: Option<String>,
    pub working_dir: Option<String>,
    pub color: Option<String>,
    pub test_command: Option<String>,
    pub lint_command: Option<String>,
    pub coverage_command: Option<String>,
    pub verify_baseline: Option<String>,
    pub review_invariants: Option<String>,
    /// Shell command of the on-demand E2E run. None = E2E not configured for the project
    /// (the button stays off). Written by update_e2e_config, not by the project form.
    pub e2e_command: Option<String>,
    /// Textual prerequisite shown before the run — Pragma does not orchestrate it (v1).
    pub e2e_precondition: Option<String>,
    /// Id of the runner chosen from the catalogue in e2e.rs (e.g. "playwright"), informational only.
    pub e2e_runner: Option<String>,
    /// Globs (one per line) of the project's sensitive surfaces. If the session diff
    /// touches one, REVIEW also gets the security hand-off (see review.rs).
    /// Empty = Pragma falls back to its default patterns.
    pub sensitive_paths: Option<String>,
    /// Category requested by the client (e.g. "Desktop app"), from the hard-wired category→stack table.
    /// Free text: no DB constraint, the catalogue lives in the code and can grow.
    pub project_category: Option<String>,
    /// Stack derived from the category (or corrected by hand). Free text — a stack outside
    /// the catalogue is legitimate, just without an automatically proposed live command.
    pub project_stack: Option<String>,
    /// Shell command of the on-demand "Live" button. None = not configured (button off).
    /// Written by the Live popup, never by the project form — same pattern as e2e_command.
    pub live_command: Option<String>,
    pub created_at: String,
    pub updated_at: String,
    pub session_count: usize,
}

pub(crate) fn open_db() -> Result<Connection> {
    let db_path = pragma_db_path()?;
    let conn =
        Connection::open(&db_path).with_context(|| format!("opening DB: {}", db_path.display()))?;
    init_db(&conn)?;
    Ok(conn)
}

